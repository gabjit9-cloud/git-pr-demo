def saluta(nome):
    # Usiamo le parentesi graffe {} per inserire la variabile nella stringa f"..."
    return f"ciao {nome}, benvenuto nel corso git!"

def somma(a, b):
    # Corretto 'rturno' in 'return'
    return a + b

# Esecuzione del codice
print(saluta("eux"))
print("risultato:", somma(5, 3))
